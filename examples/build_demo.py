#!/usr/bin/env python3
"""Build the ten-icon SCADA demo from the synthetic fixtures by running the real pipeline.

    python examples/build_demo.py --out examples/scada-demo [--review examples/pilot-review.json]
                                  [--stop-after preview]

Everything here is synthetic: the references are generated by tests/fixtures/build_fixtures.py and
the pilot review is an AGENT review recorded as such (the run was unattended). It is not a human
approval and not validation in a real application.
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCRIPTS = ROOT / "skills" / "industrial-icon-designer" / "scripts"
FIXTURES = ROOT / "tests" / "fixtures"
SET_ID = "scada-demo"
DIRECTION = ("Redraw on a 24 grid with a 1.5 stroke, round caps and joins and 2 units of padding. Keep established "
             "SCADA conventions (valve as two opposed triangles, pump as a circle with an outlet). Icons are "
             "stroke-only with currentColor, so themes and states change palette tokens and never geometry.")
STYLE_PROSE = {
    "State why this grid, stroke and palette fit the product and its smallest render size.":
        "The set is read mostly at 16 to 24 px in dense operator screens. A 24 grid with a 1.5 stroke keeps "
        "gaps open at 16 px while staying light beside text; round caps and joins match the existing family. "
        "The slate palette is provisional and is not the official brand palette.",
    "List recurring parts (arrowheads, badges, gears) and their construction rules.":
        "Equipment glyphs (pump, valve) sit on a 2 unit padding box. A discharge pipe is a 3 unit step up then "
        "a 9 unit run; a base is a 12 unit line at y=21; a valve is two opposed triangles joined at the centre "
        "with a 7 unit stem and an 8 unit handle.",
    "Record icons that deviate from the parameters above, with the reason.":
        "`settings` has an explicit 16 px variant without the four diagonal rays, because the full gear "
        "closes up at that size. No other icon deviates.",
    "Reference approved pilot icons here.":
        "All ten icons in `masters/` are the pilot. `pump` and `valve` are the reference for equipment, "
        "`trend-chart` for chart axes. The pilot review is an agent review of synthetic fixtures.",
}
SMALL_SETTINGS = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
                  'stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">'
                  '<path d="M12 3v3M12 18v3M3 12h3M18 12h3M12 8.5a3.5 3.5 0 1 0 0 7a3.5 3.5 0 0 0 0-7z"/></svg>\n')


def run(script: str, *args, check: bool = True) -> subprocess.CompletedProcess:
    proc = subprocess.run([sys.executable, str(SCRIPTS / script), *map(str, args)], capture_output=True, text=True,
                          check=False)
    if check and proc.returncode != 0:
        raise SystemExit(f"{script} {' '.join(map(str, args))} failed ({proc.returncode}):\n{proc.stderr}")
    return proc


def build(out: Path, review: Path | None, stop_after: str | None = None) -> Path:
    refs = out / "references"
    set_dir = out / "icon-work" / SET_ID
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(FIXTURES / "references", refs)
    (refs / "mystery-glyph.png").unlink()  # the ambiguous glyph is a test case, not part of the demo set
    shutil.copy(FIXTURES / "metadata.json", refs / "metadata.json")

    run("inventory_icons.py", "--input", refs, "--set", set_dir, "--set-id", SET_ID)
    run("analysis.py", "brief", "--set", set_dir, "--mode", "redraw")
    run("analysis.py", "sample", "--set", set_dir)
    run("analysis.py", "audit", "--set", set_dir, "--project-root", ROOT)
    report = set_dir / "reports" / "reference-analysis.md"
    marker = "<!-- direction:pending -->\nReplace this marker with the proposed direction and its rationale."
    report.write_text(report.read_text().replace(marker, DIRECTION))
    run("analysis.py", "finalize", "--set", set_dir)

    run("style_spec.py", "init", "--set", set_dir, "--set-id", SET_ID)
    run("style_spec.py", "generate", "--set", set_dir)
    style = set_dir / "icon-style.md"
    prose = style.read_text()
    for placeholder, text in STYLE_PROSE.items():
        prose = prose.replace(placeholder, text)
    style.write_text(prose)
    run("style_spec.py", "finalize", "--set", set_dir)

    shutil.copytree(FIXTURES / "masters", set_dir / "masters")
    (set_dir / "variants" / "small").mkdir(parents=True)
    (set_dir / "variants" / "small" / "settings.svg").write_text(SMALL_SETTINGS)
    run("render_preview.py", "--set", set_dir)
    if stop_after == "preview":
        return set_dir

    if review is None:
        raise SystemExit("--review is required to record the pilot approval")
    ids = json.loads((set_dir / "brief.json").read_text())["sample_ids"]
    scores = json.loads(review.read_text())
    missing = sorted(set(ids) - set(scores))
    if missing:
        raise SystemExit(f"review file has no scores for: {', '.join(missing)}")
    shutil.copy(review, set_dir / "reports" / "pilot-review.json")
    run("approvals.py", "record", "--set", set_dir, "--type", "pilot", "--reviewer", "agent",
        "--unattended-authorized", "--scores-file", review,
        "--note", "agent review of synthetic fixtures; not human approval")
    run("validate_icons.py", "--set", set_dir, "--phase", "source", "--project-root", ROOT)
    run("export_assets.py", "--set", set_dir)
    run("validate_icons.py", "--set", set_dir, "--phase", "exported")
    run("app_validation.py", "init", "--set", set_dir)
    run("app_validation.py", "checklist", "--set", set_dir)
    run("app_validation.py", "evaluate", "--set", set_dir)
    run("manifest.py", "status", "--set", set_dir)
    (out / "README.md").write_text(DEMO_README)
    return set_dir


DEMO_README = """# SCADA demo set (synthetic)

Generated by `examples/build_demo.py` from the synthetic fixtures. The icons are not real product
artwork. The pilot review in `icon-work/scada-demo/approvals.json` is an **agent** review recorded for an
unattended run; it is not human approval. Application validation is `not-tested` for every context.

| Path | Content |
|---|---|
| `references/` | Inconsistent synthetic "legacy" PNG/SVG icons and `metadata.json` |
| `icon-work/scada-demo/masters/` | The ten redrawn SVG masters (24 grid, `currentColor`) |
| `icon-work/scada-demo/variants/small/` | One explicit 16 px variant (`settings`) |
| `icon-work/scada-demo/icon-style.md`, `style-spec.json` | Synchronized style documents |
| `icon-work/scada-demo/preview/` | Open `index.html`; contexts are labeled simulations |
| `icon-work/scada-demo/exports/` | 160 Desktop PNGs and 10 inline Web SVGs |
| `icon-work/scada-demo/reports/` | Reference analysis, QA reports, application checklist |
| `icon-work/scada-demo/manifest.json` | Mapping from source to master to exports, with hashes |

Rebuild: `python examples/build_demo.py --out examples/scada-demo --review examples/pilot-review.json`
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True)
    ap.add_argument("--review")
    ap.add_argument("--stop-after", choices=["preview"])
    args = ap.parse_args()
    set_dir = build(Path(args.out), Path(args.review) if args.review else None, args.stop_after)
    print(f"demo built: {set_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
